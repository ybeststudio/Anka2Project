-- item.window stores the window number as the enum index: WARDROBE = 20 -> 20th member 'WARDROBE'
ALTER TABLE item MODIFY `window` enum('INVENTORY','EQUIPMENT','SAFEBOX','MALL','DRAGON_SOUL_INVENTORY','UPGRADE_INVENTORY','BOOK_INVENTORY','STONE_INVENTORY','CHANGE_INVENTORY','COSTUME_INVENTORY','CHEST_INVENTORY','SWITCHBOT','CHANGE_EQUIP','BELT_INVENTORY','GROUND','IKASHOP_OFFLINESHOP','IKASHOP_SAFEBOX','IKASHOP_AUCTION','AURA_REFINE','WARDROBE') NOT NULL;

CREATE TABLE IF NOT EXISTS wardrobe_state (
	pid INT UNSIGNED NOT NULL PRIMARY KEY,
	look0 INT UNSIGNED NOT NULL DEFAULT 0, look1 INT UNSIGNED NOT NULL DEFAULT 0, look2 INT UNSIGNED NOT NULL DEFAULT 0,
	look3 INT UNSIGNED NOT NULL DEFAULT 0, look4 INT UNSIGNED NOT NULL DEFAULT 0, look5 INT UNSIGNED NOT NULL DEFAULT 0,
	look6 INT UNSIGNED NOT NULL DEFAULT 0, look7 INT UNSIGNED NOT NULL DEFAULT 0, look8 INT UNSIGNED NOT NULL DEFAULT 0,
	remembered TINYINT UNSIGNED NOT NULL DEFAULT 0,
	applied TINYINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

CREATE TABLE IF NOT EXISTS wardrobe_outfit (
	pid INT UNSIGNED NOT NULL,
	slot TINYINT UNSIGNED NOT NULL,
	revision INT UNSIGNED NOT NULL DEFAULT 0,
	used TINYINT NOT NULL DEFAULT 0,
	name VARCHAR(96) NOT NULL DEFAULT '',
	look0 INT UNSIGNED NOT NULL DEFAULT 0, look1 INT UNSIGNED NOT NULL DEFAULT 0, look2 INT UNSIGNED NOT NULL DEFAULT 0,
	look3 INT UNSIGNED NOT NULL DEFAULT 0, look4 INT UNSIGNED NOT NULL DEFAULT 0, look5 INT UNSIGNED NOT NULL DEFAULT 0,
	look6 INT UNSIGNED NOT NULL DEFAULT 0, look7 INT UNSIGNED NOT NULL DEFAULT 0, look8 INT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (pid, slot)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;
